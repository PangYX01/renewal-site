CREATE TABLE IF NOT EXISTS ssm_renewals (
  id BIGSERIAL PRIMARY KEY,
  record_id UUID NOT NULL UNIQUE,
  form_id INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status TEXT NOT NULL DEFAULT 'pending',
  bill_id TEXT,
  registration_number TEXT NOT NULL,
  business_name TEXT NOT NULL,
  old_registration TEXT,
  verification_status TEXT,
  renewal_years INTEGER NOT NULL DEFAULT 1,
  branches INTEGER NOT NULL DEFAULT 0,
  renewal_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  branch_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
  addon_total NUMERIC(12,2) NOT NULL DEFAULT 0,
  payment_items JSONB,
  pricing_snapshot JSONB,
  extra_fields JSONB,
  total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  late_compound TEXT,
  business_info TEXT,
  colored_certificate TEXT,
  customer_name TEXT,
  email TEXT,
  phone TEXT,
  payment_url TEXT,
  source_url TEXT,
  payment_method TEXT,
  terms_agreed TEXT,
  client_browser TEXT,
  client_platform TEXT,
  client_ip TEXT,
  redirect_token TEXT,
  paid_at TIMESTAMPTZ,
  refunded_at TIMESTAMPTZ,
  transaction_id TEXT,
  transaction_status TEXT,
  payment_verified_at TIMESTAMPTZ,
  customer_email_sent_at TIMESTAMPTZ,
  admin_email_sent_at TIMESTAMPTZ,
  email_retry_count INTEGER NOT NULL DEFAULT 0,
  last_email_error TEXT,
  is_read BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ssm_renewals_created_at_idx ON ssm_renewals(created_at DESC);
CREATE INDEX IF NOT EXISTS ssm_renewals_status_idx ON ssm_renewals(status);

CREATE TABLE IF NOT EXISTS ssm_activities (
  activity_id UUID PRIMARY KEY,
  record_id UUID NOT NULL,
  event_type TEXT,
  actor TEXT,
  label TEXT,
  message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ssm_activities_record_idx ON ssm_activities(record_id, created_at DESC);
